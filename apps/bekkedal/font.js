/* Bekkedal's bitmap font.
 *
 * The app used to draw text with `ctx.fillText` at '10px monospace', which
 * meant every column position in the HUD and every menu was hand-tuned to a
 * browser-measured advance width (~6.02px) that this code could not predict.
 * Raising the internal resolution made that untenable: there is no way to
 * prove a string fits a box when only the browser knows how wide it is.
 *
 * So the glyphs live here instead, on a 5x8 cell, and the advance is an
 * integer this file owns. Uppercase occupies rows 0-6 and sits on the row-6
 * baseline; lowercase x-height runs rows 2-6 on the same baseline, and the
 * five descenders (g j p q y) spill into row 7. Ring diacritics (Å å) put the
 * ring on row 0 and compress the body beneath it.
 *
 * Two sizes are exported as scale factors rather than separate art: FONT_SM
 * for the HUD bands and the dense list menus, FONT_LG for dialogue and titles.
 * Both are integer multiples, so every glyph pixel lands on a whole screen
 * pixel at any supported resolution.
 */

export const FONT_GLYPH_W = 5;              /* ink columns in one cell        */
export const FONT_GLYPH_H = 8;              /* ink rows, incl. descender row  */
export const FONT_GAP = 1;                  /* blank columns between glyphs   */
export const FONT_LEAD = 2;                 /* blank rows between text lines  */
export const FONT_ADV = FONT_GLYPH_W + FONT_GAP;    /* 6 — one character cell */
export const FONT_LINE = FONT_GLYPH_H + FONT_LEAD;  /* 10 — one line of text  */

export const FONT_SM = 2;                   /* HUD bands, list menus          */
export const FONT_LG = 3;                   /* dialogue, panel titles         */

