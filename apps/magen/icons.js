/* every upgrade id to its family and glyph, resolved once */
export const MG_ICON = {};
(function () {
  MG_CLICK.forEach(u => MG_ICON[u.id] = { f: 'hand', g: u.ic });
  MG_KAV.forEach(u  => MG_ICON[u.id] = { f: 'kav',  g: u.ic });
  MG_DIAS.forEach(u => MG_ICON[u.id] = { f: 'dias', g: u.ic });
  MG_SPEC.forEach(u => MG_ICON[u.id] = { f: 'rule', g: u.ic });
  MG_LEG.forEach(u  => MG_ICON[u.id] = { f: 'leg',  g: u.ic });
})();

/* the frame, then the glyph, then a bright corner so it catches the eye */
export function mgUpIcon(r, id) {
  const spec = MG_ICON[id];
  if (!spec) { r(5, 5, 16, 16, 7); return; }
  const fam = MG_FAM[spec.f] || MG_FAM.rule;
  r(1, 1, 24, 24, fam.rim);
  r(2, 2, 22, 22, 0);
  r(3, 3, 20, 20, fam.bg);
  r(3, 3, 20, 1, fam.rim);
  r(3, 3, 1, 20, fam.rim);
  const gl = MG_G[spec.g];
  if (gl) gl(r); else { r(9, 9, 8, 8, 15); }
  r(1, 1, 3, 1, 15); r(1, 1, 1, 3, 15);
}

/* a building's own icon with a row of pips for how many tiers are on it */
export function mgTierIcon(r, bid, tier) {
  r(1, 1, 24, 24, 14); r(2, 2, 22, 22, 0);
  mgIcon((x, y, w, h, c) => r(2 + x * 0.84, 1 + y * 0.84, Math.max(1, w * 0.84), Math.max(1, h * 0.84), c), bid);
  r(0, 21, 26, 5, 0);
  for (let i = 0; i < 5; i++) r(2 + i * 5, 22, 4, 3, i < tier ? 14 : 8);
}

